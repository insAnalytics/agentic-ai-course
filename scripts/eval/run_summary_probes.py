def mentions(answer: str, phrase: str) -> bool:
    """Whether the answer contains the phrase as whole words, ignoring case. A phrase ending in a digit may be
    followed by a unit ("1750" matches "1750ms"), the same rule as grading.py's matcher version 2."""
    end = r"(?![0-9]|[.,][0-9])" if phrase[-1].isdigit() else r"(?![\w-])"
    return re.search(rf"(?<![\w-]){re.escape(phrase.lower())}{end}", answer.lower()) is not None


def correct(item: dict, answer: str) -> bool:
    any_ok = not item["any"] or any(mentions(answer, p) for p in item["any"])
    return any_ok and all(mentions(answer, p) for p in item["all"])


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--agent-url", default="http://localhost:8000")
    parser.add_argument("--workers", type=int, default=32)
    args = parser.parse_args()
    first = json.loads(SUMMARIES.read_text(encoding="utf-8"))
    if set(PROBES) != {t["trial_id"] for t in first["traces"]}:
        sys.exit("the probes don't cover exactly the first round's traces")
    repo, revision = MODELS["4b"]
    template, template_check = ChatTemplate.qwen35(), None
    if args.dry_run:
        backend = StandInText()
    else:
        from huggingface_hub import hf_hub_download
        from transformers import AutoTokenizer
        from backends import VLLMBackend
        tokenizer = AutoTokenizer.from_pretrained(repo, revision=revision)
        template = ChatTemplate(Path(hf_hub_download(repo, "chat_template.jinja", revision=revision)).read_text(encoding="utf-8"))
        template_check = check_template(template, tokenizer, False)
        if not template_check:
            sys.exit("our template rendering differs from transformers'")
        backend = VLLMBackend(args.agent_url, repo, tokenizer)

    def one(job):
        result, n = job
        item = PROBES[result["trial_id"]][n]
        reader = ModelClient(backend, template, PROBE_SYSTEM, [], False, PROBE_SAMPLING, 64,
                             seed_for("probe2", result["trial_id"], result["variant"], result["sample"], n))
        reply = reader.create([{"role": "user", "content": f"{result['summary']}\n\nUsing only the summary above: {item['question']}"}])
        text = " ".join(b.text for b in reply.content if b.type == "text").strip()
        return {"trial_id": result["trial_id"], "variant": result["variant"], "sample": result["sample"], "probe": n,
                "answer": text, "correct": correct(item, text)}

    jobs = [(r, n) for r in first["results"] for n in range(len(PROBES[r["trial_id"]]))]
    started = time.monotonic()
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        answers = list(pool.map(one, jobs))
    wall = time.monotonic() - started
    run = {"dry_run": args.dry_run, "model": repo, "revision": revision, "summaries": str(SUMMARIES.relative_to(ROOT)),
           "probe_system": PROBE_SYSTEM, "probe_sampling": PROBE_SAMPLING, "template_matches_transformers": template_check,
           "setup": {"agent_server": backend.server_info(), "gpus": gpu_names()}, "timing": {"wall_seconds": round(wall, 3)},
           "probes": PROBES, "answers": answers}
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"summary-probes{'.dry-run' if args.dry_run else ''}.json"
    path.write_text(json.dumps(run, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    for variant in first["instructions"]:
        marks = [a["correct"] for a in answers if a["variant"] == variant]
        print(f"{variant}: {sum(marks)} of {len(marks)} probe answers right")
    print(f"{len(answers)} answers in {wall:.1f}s -> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
